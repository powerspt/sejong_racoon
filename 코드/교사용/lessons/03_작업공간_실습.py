from roboid import *

바퀴 = Raccoon()
바퀴.unit("cm")
바퀴.end_effector("gripper")
바퀴.lock_horz()

높이들 = [3, 8, 15]         # 이 세 높이의 단면도를 그린다
간격 = 1.0                  # 몇 cm 씩 훑을까


def 갈_수_있나(x, y, z):
    """(x, y, z) 에 갈 수 있는가"""
    # TODO 1 ─ can_move_to 로 물어보고 True/False 를 돌려주시오.
    #   주의: bool() 로 감싸 두면 나중에 세기 편하다.
    return False


def 단면도(z):
    """높이 z 의 단면도를 글자로 그린다.  O = 갈 수 있음, . = 못 감"""
    print(f"\n── 높이 {z}cm ──")
    칸수 = 0

    # y 는 뒤(위쪽 줄)부터 앞(아래쪽 줄)으로 그려야 화면이 실제 배치와 같아진다
    y = 28.0
    while y >= 2.0:
        줄 = ""
        x = -24.0
        while x <= 24.0:
            # TODO 2 ─ 이 (x, y, z) 가 갈 수 있는 곳이면 "O", 아니면 "." 을 줄에 붙이시오.
            #   그리고 갈 수 있으면 칸수도 1 늘리시오.
            #   힌트: 되나 = 갈_수_있나(x, y, z)  로 받아 두면 두 번 쓰기 편하다
            줄 += "?"

            x += 간격
        print(f"{y:>5.0f} |{줄}")
        y -= 간격

    가운데 = int(round(24.0 / 간격))        # 줄에서 x=0 이 놓인 칸 번호
    print(" " * 7 + " " * 가운데 + "^ x=0 (로봇 원점)")
    print(f"      갈 수 있는 칸 {칸수}개")


for z in 높이들:
    단면도(z)

바퀴.dispose()


