"""주제 2 — 순기구학 (기본)

관절 각도를 알 때 집게 끝이 어디에 있는지 **직접 계산**한다.

    python lessons/02_순기구학_기본.py

이 파일은 '돌아가는 최소본' 이다. 그대로 실행하면 결과가 나온다.
맨 아래 '여기서 더 해볼 것' 을 보고 고쳐 나가면 된다.
"""
import math

# 라쿤봇의 길이 (cm). 매뉴얼 1장
L1 = 8.25       # 바닥 ~ 어깨
L2 = 10.0       # 어깨 ~ 팔꿈치
L3 = 10.0       # 팔꿈치 ~ 손목
GRIP = 8.0      # 손목 ~ 집게 끝 (앞으로)


def 순기구학(j1, j2, j3, j4):
    """관절 각도 4개 -> 집게 끝 (x, y, z) cm

    옆에서 본 그림으로 생각하면 쉽다.
      어깨에서 j2 만큼 기울어진 막대 L2
      그 끝에서 j2+j3 만큼 기울어진 막대 L3
      그 끝에서 j2+j3+j4 만큼 기울어진 막대 GRIP
    각 막대의 '앞으로 간 거리' 와 '올라간 높이' 를 더하면 된다.
    """
    a2 = math.radians(j2)
    a3 = math.radians(j2 + j3)
    a4 = math.radians(j2 + j3 + j4)

    # 옆에서 봤을 때 앞으로 간 거리 r 과 높이 z
    # roboid 는 관절 각도의 +를 '뒤로 젖히는 쪽' 으로 잡는다 (j2 는 -90 ~ +30).
    # 그래서 앞으로 간 거리는 부호를 뒤집어 준다.
    r = -(L2 * math.sin(a2) + L3 * math.sin(a3) + GRIP * math.sin(a4))
    z = L1 + L2 * math.cos(a2) + L3 * math.cos(a3) + GRIP * math.cos(a4)

    # 위에서 봤을 때 j1 만큼 돌린다 (j1 이 +면 왼쪽 = x 가 -)
    a1 = math.radians(j1)
    x = -r * math.sin(a1)
    y = r * math.cos(a1)
    return x, y, z


자세들 = [
    ("Home", (0, -10, -140, 60)),
    ("팔 펴기", (0, -45, -90, 45)),
    ("왼쪽으로", (30, -20, -120, 40)),
]

print(f"{'자세':<10}{'관절 (j1,j2,j3,j4)':<26}{'x':>8}{'y':>8}{'z':>8}")
for 이름, 각도 in 자세들:
    x, y, z = 순기구학(*각도)
    print(f"{이름:<10}{str(각도):<26}{x:>8.2f}{y:>8.2f}{z:>8.2f}")

print()
