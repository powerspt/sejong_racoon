"""주제 3 — 작업 공간 (기본)

로봇이 **갈 수 있는 곳과 없는 곳의 경계**를 직접 찾는다.

    python lessons/03_작업공간_기본.py

로봇이 연결돼 있어야 한다. 팔은 움직이지 않는다 (can_move_to 는 물어보기만 한다).
"""
from roboid import *

바퀴 = Raccoon()
바퀴.unit("cm")
바퀴.end_effector("gripper")
바퀴.lock_horz()            # 집게를 수평으로 고정. 기울기가 바뀌면 답도 바뀐다

높이 = 5.0                  # 이 높이에서 찾는다 (cm)


def 갈_수_있나(y):
    """로봇 정면(x=0)으로 y cm 떨어진 곳에 갈 수 있는가"""
    return 바퀴.can_move_to(0, y, 높이)


# 1cm 씩 늘려 가며 어디부터 어디까지 갈 수 있는지 본다
print(f"높이 {높이}cm, 로봇 정면(x=0)")
print()
print(f"{'거리(cm)':>8}  갈 수 있나")
갈_수_있는_곳 = []
for y in range(3, 31):
    되나 = 갈_수_있나(y)
    print(f"{y:>8}  {'O' if 되나 else '.'}")
    if 되나:
        갈_수_있는_곳.append(y)

print()
if 갈_수_있는_곳:
    print(f"갈 수 있는 범위: {min(갈_수_있는_곳)} ~ {max(갈_수_있는_곳)} cm")
else:
    print("갈 수 있는 곳이 없다")

바퀴.dispose()


