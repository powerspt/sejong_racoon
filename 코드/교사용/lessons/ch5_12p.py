"""주제 5 · 12페이지 — 반복정밀도(같은 명령을 되풀이했을 때 흩어지는 정도) 측정 (숫자만 바꿔 실행)

    python lessons/ch5_12p.py

z_펜 높이로 10번 반복해 C2 에 점 10개를 찍는다.
칸을 바꾸려면 x, y 를 — 먼 칸 A4 = (-16, 20), 가까운 칸 E3 = (0, 16).

**펜은 고무줄이 잡는다.** 집게의 쥐는 힘으로는 눌리는 순간 미끄러진다.
집게는 닫아 두기만 하고 하중은 고무줄이 받는다.

**집게는 눕힌 채(수평) 쓴다.** 벌어진 턱 사이에 펜을 세워 넣고 고무줄로 감는다.
먼 칸 A4 까지 가야 해서 집게를 세우지 않는다 (세운 집게는 반경 18.5cm 까지만 닿는다).
02_눈금자 는 집게를 아래로 세워 쓴다 — 거기서 잰 Z_DRAW 는 여기에 맞지 않는다.

**펜은 집게 아래 면에서 3.5cm 쯤 나오게 물린다.** 그러면 z_펜 = 4.0 쯤에서 종이에 닿는다
(눕힌 집게의 아래 면은 z 보다 0.5cm 쯤 낮다). z 는 펜 끝 높이가 아니다 —
처음에는 0.5 높게 넣고 내려 가며 맞춘다.

**1.5 아래로는 내리지 않는다** — 집게를 아래로 세우면 z 1.5 에서 손가락이 책상에 닿는다 (눕힌 집게는 0.6 쯤).
"""
from roboid import *

raccoon = Raccoon()

x, y = -8, 12     # C2 칸
z_펜 = 4.0        # ← 집게 아래 면에서 펜이 3.5cm 쯤 나왔을 때의 값 (1.5 아래 금지)

# 펜 물리기 — 집게는 눕힌 채, 턱 사이에 펜을 세워 넣고 고무줄로 감는다
#   팔을 세운 자세에서 물린다 — 바로 앞으로 뻗으면 가는 길에 집게가 바닥을 스친다
raccoon.degree_to(0, -10, -70, -10, 20)    # 끝 숫자는 속도
raccoon.open_gripper()
input("고무줄로 감았으면 (이미 물렸으면 그대로) Enter > ")
raccoon.close_gripper()

for i in range(10):
    raccoon.degree_to(0, -10, -70, -10)   # 팔을 세운 뒤 간다 (먼 칸으로 바로 가면 바닥을 스친다)
    raccoon.move_to(x, y, 10)
    raccoon.move_to(x, y, z_펜, 20)   # 콕!
    raccoon.beep()
    raccoon.move_to(x, y, 10)
    raccoon.degree_to(0, -10, -140, 60)   # 홈에서 다시 출발

raccoon.dispose()
