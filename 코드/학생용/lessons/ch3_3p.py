"""주제 3 — 칸 이름으로 보내기. 집게에 실 + 클립을 매달아 어디에 섰는지 눈으로 확인하기
`Raccoon()` 은 연결하면서 **집게를 연다**. 그러니 연결한 뒤에
실을 끼우고 닫아야 한다. 미리 물려 두면 연결하는 순간 떨어진다.
"""
from roboid import *

X = [-16, -12, -8, -4, 0, 4, 8, 12, 16]  # A3 열 A~I
Y = [8, 12, 16, 20]                      # 행 1~4
Z = 10                                   # 칸 위 접근 높이 (수평 구역)
UP = (0, -10, -70, -10)                  # 지나다닐 때 팔을 세우는 자세

cell = "E3"                              # ← 여기를 바꿔 본다
x = X[ord(cell[0]) - ord("A")]
y = Y[int(cell[1]) - 1]

raccoon = Raccoon()          # 연결하면서 집게가 열리고 Home 으로 간다
raccoon.lock_horz()          # 집게를 지면과 나란히 — 추가 똑바로 내려온다

input("집게 사이에 실 끝을 끼우고 Enter >> ")
raccoon.close_gripper()      # 두 날이 만나는 점에 실이 물린다

if not raccoon.can_move_to(x, y, Z):
    # 수평 집게는 가까운 칸에 못 간다 — 손목이 105° 한계에 걸린다.
    # 범위 밖이면 로봇은 삐 소리만 내고 가만히 있으므로 미리 걸러 준다.
    print(cell, (x, y), "→ 못 가는 칸이다. 수평 집게의 작업 공간 밖이다")
else:
    th1 = raccoon.xyz_to_degree(x, y, Z)[0]      # 그 칸을 보려면 베이스를 몇 도로?
    raccoon.degree_to(0, -10, -70, -10, 40)      # ① 팔을 세우고
    raccoon.degree_to(th1, -10, -70, -10, 40)    # ② 그 높이에서 베이스만 돌린 뒤
    raccoon.move_to(x, y, Z, 40)                 # ③ 칸 위로 내려온다
    print(cell, (x, y), "→ 실제", raccoon.xyz())
    input("추 끝과 십자가 겹치는지 보고 Enter >> ")
    raccoon.degree_to(th1, -10, -70, -10, 40)    # 올라와서

raccoon.degree_to(0, -10, -140, 60, 40)          # Home 으로
raccoon.dispose()

# 왜 세 걸음으로 가는가
#   한 번에 보내면 움직일 각도가 제일 큰 관절만 늦게 도착한다. 보통 어깨가 먼저
#   눕고 팔꿈치가 뒤늦게 펴지면서 집게가 테이블을 긁는다. 먼 칸일수록 심하다 —
#   Home 에서 A4·I4 로 바로 보내면 가는 길에 집게 끝이 테이블 아래(-0.3cm)를
#   지나려 든다. 팔을 세운 채 돌고 나서 내려오면 36칸 어디로 가도 6.9cm 위로 지난다.
#
# 수평 집게로 못 가는 칸 (계산값, 실기 확인 전)
#   C1 D1 E1 F1 G1 E2 — 로봇에 너무 가까워 손목이 안 꺾인다.
#   이 칸들을 집으려면 lock_vert() 로 수직으로 내려 잡는다. 주제 3 의 "갈 수 있는
#   곳과 없는 곳" 이 바로 이 이야기다.
